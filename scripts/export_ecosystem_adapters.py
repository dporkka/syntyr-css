"""Generate opt-in Tailwind, Figma and VS Code artifacts from Syntyr CSS sources.

Uses only the Python standard library; no application runtime dependencies.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

if __package__:
    from .export_api_metadata import outputs as api_outputs
else:
    from export_api_metadata import outputs as api_outputs

ROOT = Path(__file__).resolve().parents[1]
PALETTES = ("studio", "grid", "noir", "industrial", "terminal", "corporate", "minimal")
COLORS = ("bg", "surface", "surface-hi", "text", "muted", "accent", "accent-2",
          "on-accent", "frame", "frame-strong", "danger", "success", "warning")
DIMENSIONS = ("radius", "cut")
DECLARATION = re.compile(r"^\s*(--syn-[\w-]+):\s*([^;]+);")
CSS_COMMENT = re.compile(r"/\*.*?\*/", re.DOTALL)
THEME_NAME = re.compile(r'data-syn-theme="([a-z]+)"')
HEX_COLOR = re.compile(r"^#[0-9a-fA-F]{6}$")
REM_VALUE = re.compile(r"^((?:\d+(?:\.\d*)?|\.\d+))rem$")


def read_palettes(css: str, *, strict: bool = True) -> dict[str, dict[str, str]]:
    """Read source palettes; strict mode requires literal public design tokens.

    Non-strict mode is for diagnostics: it retains missing and nonliteral
    declarations so the caller can report individual actionable failures.
    """
    result: dict[str, dict[str, str]] = {}
    current = None
    # CSS ignores declarations inside block comments; audit the same active text.
    for line in CSS_COMMENT.sub("", css).splitlines():
        stripped = line.strip()
        if current is not None:
            if stripped == "}":
                current = None
            else:
                match = DECLARATION.match(line)
                if match:
                    result[current][match.group(1)] = match.group(2).strip()
            continue
        if stripped.startswith(":where(") and stripped.endswith("{"):
            names = THEME_NAME.findall(stripped)
            if names and names[0] in PALETTES:
                name = names[0]
                if name in result:
                    raise ValueError(f"Repeated explicit palette: {name}")
                result[name] = {}
                current = name
    if current is not None:
        raise ValueError(f"Unclosed theme block: {current}")
    if set(result) != set(PALETTES):
        raise ValueError(f"Expected {PALETTES}, found {sorted(result)}")
    if not strict:
        return result
    for name, palette in result.items():
        for token in COLORS:
            value = palette.get(f"--syn-{token}", "")
            if not HEX_COLOR.fullmatch(value):
                raise ValueError(f"{name}: missing or non-literal color --syn-{token}: {value}")
        for token in DIMENSIONS:
            value = palette.get(f"--syn-{token}", "")
            if value != "0" and REM_VALUE.fullmatch(value) is None:
                raise ValueError(f"{name}: unsupported dimension --syn-{token}: {value}")
    return result


def figma_color(hex_value: str) -> dict:
    components = [round(int(hex_value[i:i + 2], 16) / 255, 8) for i in (1, 3, 5)]
    return {"$type": "color", "$value": {
        "colorSpace": "srgb", "components": components,
        "alpha": 1, "hex": hex_value.upper(),
    }}


def figma_dimension(value: str) -> dict:
    px = 0 if value == "0" else round(float(REM_VALUE.fullmatch(value).group(1)) * 16, 5)
    return {"$type": "dimension", "$value": {"value": px, "unit": "px"}}


def as_json(payload: dict) -> str:
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def outputs() -> dict[Path, str]:
    palettes = read_palettes((ROOT / "src/tokens.css").read_text(encoding="utf-8"))
    artifacts: dict[Path, str] = {}
    bridge = [
        "/* Generated by scripts/export_ecosystem_adapters.py. Tailwind v4 opt-in only.",
        " * Import into a Tailwind CSS entrypoint AFTER Tailwind, and load Syntyr core.",
        " * Utilities resolve the nearest scoped --syn-* value at the element. */",
        "@theme inline {",
    ]
    bridge.extend(f"  --color-syntyr-{name}: var(--syn-{name});" for name in COLORS)
    bridge.extend(["}", ""])
    artifacts[ROOT / "integrations/tailwind/syntyr.theme.css"] = "\n".join(bridge)
    for name in PALETTES:
        palette = palettes[name]
        figma = {token: figma_color(palette[f"--syn-{token}"]) for token in COLORS}
        figma.update({token: figma_dimension(palette[f"--syn-{token}"])
                      for token in DIMENSIONS})
        artifacts[ROOT / f"metadata/figma/syntyr-{name}.tokens.json"] = as_json(figma)

    extension = ROOT / "integrations/vscode"
    source_files = {p.name: content for p, content in api_outputs().items()}
    for filename in ("syntyr.html-custom-data.json", "syntyr.css-custom-data.json"):
        artifacts[extension / "metadata" / filename] = source_files[filename]
    artifacts[extension / "snippets/syntyr.code-snippets"] = source_files["syntyr.code-snippets"]
    version = (ROOT / "VERSION").read_text(encoding="utf-8").strip().removeprefix("v")
    package = {
        "name": "syntyr-css",
        "displayName": "Syntyr CSS (local preview)",
        "description": "Syntyr HTML/CSS custom data and snippets, with no extension runtime.",
        "version": version,
        "publisher": "syntyr-local",
        "license": "MIT",
        "repository": {"type": "git", "url": "https://github.com/dporkka/syntyr-css.git"},
        "files": ["metadata/", "snippets/", "README.md", "LICENSE"],
        "engines": {"vscode": "^1.90.0"},
        "categories": ["Snippets", "Other"],
        "contributes": {
            "html": {"customData": ["./metadata/syntyr.html-custom-data.json"]},
            "css": {"customData": ["./metadata/syntyr.css-custom-data.json"]},
            "snippets": [
                {"language": language, "path": "./snippets/syntyr.code-snippets"}
                for language in ("html", "javascriptreact", "typescriptreact")
            ],
        },
    }
    artifacts[extension / "package.json"] = as_json(package)
    artifacts[extension / "LICENSE"] = (ROOT / "LICENSE").read_text(encoding="utf-8")
    artifacts[extension / "README.md"] = ("# Syntyr CSS — local VS Code integration\n\n"
        "Bundles generated HTML/CSS custom data and snippets. No extension runtime.\n\n"
        "This local preview is not published to the VS Code Marketplace.\n"
        "See ../../docs/ecosystem-integrations.md in the source repository.\n")
    return artifacts


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files match source")
    args = parser.parse_args(argv)
    stale = False
    for path, content in outputs().items():
        if args.check:
            valid = path.is_file() and path.read_text(encoding="utf-8") == content
            print(f"{'OK' if valid else 'STALE'} {path.relative_to(ROOT)}")
            stale |= not valid
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"WROTE {path.relative_to(ROOT)}")
    return int(stale)


if __name__ == "__main__":
    sys.exit(main())
