"""Build a deterministic, public-only consolidated LLM reference (stdlib only).

The source list is explicit: no repository-wide crawler can publish private docs.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "llms-full.txt"
SOURCES = (
    "docs/ai-quickstart.md",
    "docs/design-principles.md",
    "docs/components.md",
    "docs/data-grid.md",
    "docs/recipes.md",
    "docs/component-recipes.md",
    "docs/native-patterns.md",
    "docs/semantic-components.md",
    "docs/composition-adoption.md",
    "docs/radix-integration.md",
    "docs/distribution.md",
    "docs/from-pico.md",
    "docs/api-stability.md",
    "docs/framework-integrations.md",
    "docs/site-builders.md",
    "docs/mobile-frameworks.md",
    "docs/native-browser-apis.md",
    "docs/interaction-recipes.md",
    "docs/dropdowns.md",
    "docs/theme-customization.md",
    "docs/visual-intensity.md",
    "docs/visual-composition.md",
    "docs/geometry-terminal.md",
    "docs/ascii-effects.md",
    "docs/viz.md",
    "docs/geo.md",
    "docs/accessibility.md",
    "docs/agent-integration.md",
    "docs/editor-integration.md",
)


def render() -> str:
    version = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
    if not version or "/" in version or "\\" in version:
        raise ValueError("Invalid source version")
    lines = [
        "# Syntyr CSS — consolidated public reference",
        "",
        f"Source-tree version: {version} (may be an unreleased candidate).",
        "Published immutable release: 0.3.0-alpha.4.",
        "",
        "WARNING: This reference follows repository source. Before generating markup,",
        "check the installed release and CSS modules. Do not assume alpha.5 features",
        "exist in the published alpha.4 release. Syntyr is CSS, not a JS widget library.",
        "",
        "Generated from an explicit allowlist by scripts/build_agent_docs.py.",
        "Do not edit this file directly.",
        "Relative links below are relative to each original source file, not this combined file.",
        "",
    ]
    for path in SOURCES:
        source = ROOT / path
        if source.is_symlink() or not source.is_file() or not source.resolve().is_relative_to(ROOT):
            raise ValueError(f"Invalid public source file: {path}")
        source_url = f"https://syntyr-css.pages.dev/{path}"
        lines.extend([f"---\n\n## Source: {path}\n\nOriginal: {source_url}\n",
                      source.read_text(encoding="utf-8").strip(), ""])
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if llms-full.txt is stale")
    args = parser.parse_args()
    result = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != result:
            print("STALE llms-full.txt; run python3 scripts/build_agent_docs.py", file=sys.stderr)
            return 1
        print(f"OK llms-full.txt ({len(result.encode('utf-8'))} bytes)")
        return 0
    OUTPUT.write_text(result, encoding="utf-8")
    print(f"WROTE llms-full.txt ({len(result.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
