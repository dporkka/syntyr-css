"""Export Syntyr's literal CSS tokens as portable, framework-neutral mobile values.

No CSS parser, Node toolchain, React Native dependency, or codegen runtime is required.
Only literal colors and rem dimensions are exported; browser-dependent CSS stays web-only.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

if __package__:
    from .export_ecosystem_adapters import COLORS, PALETTES, read_palettes, REM_VALUE
else:
    from export_ecosystem_adapters import COLORS, PALETTES, read_palettes, REM_VALUE

ROOT = Path(__file__).resolve().parents[1]
BASE = re.compile(r":where\(\.syn-root\)\s*\{([^}]+)\}", re.DOTALL)
DECL = re.compile(r"(--syn-[\w-]+):\s*([^;]+);")
ROOT_REM = 16


def to_points(value: str) -> int | float:
    """Map literal CSS rem to numeric design points using a 16px web root."""
    if value == "0":
        return 0
    match = REM_VALUE.fullmatch(value)
    if not match:
        raise ValueError(f"Cannot export nonliteral native dimension: {value}")
    points = round(float(match.group(1)) * ROOT_REM, 5)
    return int(points) if points.is_integer() else points


def mobile_tokens(css: str) -> dict:
    match = BASE.search(css)
    if not match:
        raise ValueError("Missing scoped base Syntyr tokens")
    base = dict(DECL.findall(match.group(1)))
    palettes = read_palettes(css)
    spaces = {str(n): to_points(base[f"--syn-space-{n}"]) for n in range(1, 6)}
    sizes = {size: to_points(base[f"--syn-type-{size}"])
             for size in ("xs", "sm", "base")}
    return {
        "schemaVersion": 1,
        "unit": "logical-points",
        "source": "src/tokens.css",
        "webRemBaselinePx": ROOT_REM,
        "spacing": spaces,
        "fontSize": sizes,
        "controlHeight": to_points(base["--syn-control-height"]),
        "themes": {
            theme: {
                "colors": {role: palettes[theme][f"--syn-{role}"] for role in COLORS},
                "radius": to_points(palettes[theme]["--syn-radius"]),
                "cut": to_points(palettes[theme]["--syn-cut"]),
            } for theme in PALETTES
        },
    }


def outputs() -> dict[Path, str]:
    payload = mobile_tokens((ROOT / "src/tokens.css").read_text(encoding="utf-8"))
    json_payload = json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
    ts_payload = (
        "// Generated by scripts/export_mobile_tokens.py; do not edit.\n"
        "// Framework-neutral numeric/color tokens; no native runtime dependency.\n"
        "export const syntyrMobileTokens = " + json.dumps(payload, indent=2, ensure_ascii=False)
        + " as const;\n\n"
        "export type SyntyrMobileTheme = keyof typeof syntyrMobileTokens.themes;\n"
    )
    return {
        ROOT / "metadata/mobile/syntyr.tokens.json": json_payload,
        ROOT / "integrations/react-native/tokens.ts": ts_payload,
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify checked-in artifacts")
    args = parser.parse_args(argv)
    stale = False
    for path, output in outputs().items():
        if args.check:
            current = path.read_text(encoding="utf-8") if path.is_file() else None
            valid = current == output
            print(f"{'OK' if valid else 'STALE'} {path.relative_to(ROOT)}")
            stale |= not valid
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(output, encoding="utf-8")
            print(f"WROTE {path.relative_to(ROOT)}")
    return int(stale)


if __name__ == "__main__":
    sys.exit(main())
